local seed = 1
local function rnd() seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648 end

local function pixels(rows)
  local px = {}
  for y, row in ipairs(rows) do
    for x = 1, #row do
      if row:sub(x, x) == "#" then px[(y - 1) * W + (x - 1)] = true end
    end
  end
  return px
end

-- Vertical offset per glyph per frame: frame 0 sits on the middle line, the others hop by a pixel.
local function hop(f)
  if f == 0 then return 1 end
  local r = rnd()
  return r < 0.4 and 0 or (r < 0.8 and 2 or 1)
end

local FRAMES = 3
local img = Image(W * 95, H * FRAMES, ColorMode.RGB)
for i = 0, 94 do
  local ch = string.char(32 + i)
  local rows = G[ch]
  assert(rows, "missing glyph " .. ch)
  local px = pixels(rows)
  for f = 0, FRAMES - 1 do
    seed = i * 31 + f * 7919 + 17
    for _ = 1, 3 do rnd() end
    local dy = hop(f)
    for k in pairs(px) do img:drawPixel(i * W + k % W, f * H + k // W + dy, INK) end
  end
end

local spr = Sprite(img.width, img.height, ColorMode.RGB)
spr:newCel(spr.layers[1], 1, img, Point(0, 0))
spr:saveAs("art/font.aseprite")
spr:saveCopyAs("assets/font@6x11.png")
spr:close()
